#!/usr/bin/env node
// Builds src/content/blog.ts from docs/research/skyfall.ai/posts-source.json, keeping the site's post order.
// Usage: node scripts/generate-blog-data.mjs

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE = fileURLToPath(new URL("../docs/research/skyfall.ai/posts-source.json", import.meta.url));
const TARGET = fileURLToPath(new URL("../src/content/blog.ts", import.meta.url));

const posts = JSON.parse(await readFile(SOURCE, "utf8")).map((post) => ({
  slug: post.slug,
  title: post.title,
  author: post.author,
  date: post.date,
  iso: post.iso,
  minutes: post.minutes,
  hero: post.hero,
  thumb: post.thumb,
  heroAlt: post.heroAlt,
  caption: post.caption,
  chips: post.chips,
  excerpt: post.excerpt,
  toc: post.toc.map(({ id, title }) => ({ id, title })),
  html: post.html,
  ...(post.embed && {
    embed: { styles: post.embed.styles, modules: post.embed.modules, scripts: post.embed.scripts },
  }),
}));

await writeFile(
  TARGET,
  `// Generated by scripts/generate-blog-data.mjs — do not edit.
export interface BlogPost {
  slug: string;
  title: string;
  author: string;
  date: string;
  iso: string;
  minutes: number;
  hero: string;
  thumb: string;
  heroAlt: string;
  caption: string;
  chips: string[];
  excerpt: string;
  toc: { id: string; title: string }[];
  html: string;
  embed?: { styles: string[]; modules: string[]; scripts: string[] };
}

export const posts: BlogPost[] = ${JSON.stringify(posts, null, 2)};

export const getPost = (slug: string) => posts.find((post) => post.slug === slug);

export const isEmbedPost = (post: BlogPost): post is BlogPost & Required<Pick<BlogPost, "embed">> =>
  post.embed !== undefined;
`,
);

console.log(`Wrote ${posts.length} posts to src/content/blog.ts: ${posts.map((post) => post.slug).join(", ")}`);
