export interface PixelTone {
  color: string;
  ghost: string;
}

export function pixelTone(hex: string): PixelTone {
  const n = parseInt(hex.slice(1), 16);
  const ghost = [n >> 16, (n >> 8) & 255, n & 255].map((c) => Math.round(c + (255 - c) * 0.65)).join(",");
  return { color: hex, ghost: `rgb(${ghost})` };
}

